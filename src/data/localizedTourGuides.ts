export function getLocalizedOrigins(locale: Locale): GuideOrigin[] {
  if (locale === 'bn') {
    return BASE_ORIGINS.map((orig) => {
      const tr = BENGALI_ORIGINS[orig.id];
      if (tr) {
        return {
          ...orig,
          name: tr.name || orig.name,
          district: tr.district || orig.district,
          departureHubs: tr.departureHubs || orig.departureHubs,
        };
      }
      return orig;
    });
  }
  return BASE_ORIGINS;
}

export function getLocalizedDestinations(locale: Locale): GuideDestination[] {
  if (locale === 'bn') {
    return BASE_DESTINATIONS.map((dest) => {
      const tr = BENGALI_DESTINATIONS[dest.id];
      if (tr) {
        return {
          ...dest,
          name: tr.name || dest.name,
          tagline: tr.tagline || dest.tagline,
          region: tr.region || dest.region,
          category: tr.category || dest.category,
          overview: tr.overview || dest.overview,
          highlights: tr.highlights || dest.highlights,
        };
      }
      return dest;
    });
  }
  return BASE_DESTINATIONS;
}

